// tokgen probes the exact unicode61 tokenizer of the SQLite build the product
// links (modernc.org/sqlite v1.58.0) for every Unicode scalar value and writes
// a Rust table: separator ranges and per-codepoint folds.
package main

import (
	"bufio"
	"encoding/json"
	"database/sql"
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode/utf8"

	_ "modernc.org/sqlite"
)

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func main() {
	if len(os.Args) == 3 && os.Args[1] == "tok" {
		tokLines(os.Args[2])
		return
	}
	db, err := sql.Open("sqlite", ":memory:")
	must(err)
	db.SetMaxOpenConns(1)
	var ver string
	must(db.QueryRow(`select sqlite_version()`).Scan(&ver))
	_, err = db.Exec(`CREATE VIRTUAL TABLE tok USING fts5(name, qualified_name, signature, path, body, tokenize='unicode61', detail='full')`)
	must(err)
	_, err = db.Exec(`CREATE VIRTUAL TABLE tok_vocab USING fts5vocab(tok, 'instance')`)
	must(err)
	tx, err := db.Begin()
	must(err)
	ins, err := tx.Prepare(`INSERT INTO tok(rowid, body) VALUES(?, ?)`)
	must(err)
	for cp := rune(0); cp <= 0x10FFFF; cp++ {
		if cp >= 0xD800 && cp <= 0xDFFF {
			continue
		}
		_, err := ins.Exec(int64(cp)+1, "a"+string(cp)+"b")
		must(err)
	}
	// Token-length probe: one 40 000-byte token, and a long one ending in a multibyte char.
	_, err = ins.Exec(int64(0x200000), strings.Repeat("a", 40000))
	must(err)
	_, err = ins.Exec(int64(0x200001), strings.Repeat("a", 32767)+"é")
	must(err)
	must(tx.Commit())
	rows, err := db.Query(`SELECT doc, term FROM tok_vocab ORDER BY doc, offset`)
	must(err)
	toks := map[int64][]string{}
	for rows.Next() {
		var d int64
		var t string
		must(rows.Scan(&d, &t))
		toks[d] = append(toks[d], t)
	}
	must(rows.Err())
	for _, d := range []int64{0x200000, 0x200001} {
		for _, t := range toks[d] {
			fmt.Fprintf(os.Stderr, "probe %x: token of %d bytes, ends %q\n", d, len(t), t[len(t)-3:])
		}
	}
	type fold struct {
		cp  rune
		out string
	}
	var seps [][2]rune
	var folds []fold
	anomalies := 0
	for cp := rune(0); cp <= 0x10FFFF; cp++ {
		if cp >= 0xD800 && cp <= 0xDFFF {
			continue
		}
		t := toks[int64(cp)+1]
		switch {
		case len(t) == 2 && t[0] == "a" && t[1] == "b":
			if n := len(seps); n > 0 && seps[n-1][1] == cp-1 {
				seps[n-1][1] = cp
			} else if n > 0 && seps[n-1][1] == 0xD7FF && cp == 0xE000 {
				seps[n-1][1] = cp
			} else {
				seps = append(seps, [2]rune{cp, cp})
			}
		case len(t) == 1 && strings.HasPrefix(t[0], "a") && strings.HasSuffix(t[0], "b") && len(t[0]) >= 2:
			x := t[0][1 : len(t[0])-1]
			if utf8.RuneCountInString(x) > 1 {
				anomalies++
				fmt.Fprintf(os.Stderr, "multi-rune fold U+%04X: %q\n", cp, x)
			} else if x != string(cp) {
				folds = append(folds, fold{cp, x})
			}
		default:
			anomalies++
			if anomalies < 20 {
				fmt.Fprintf(os.Stderr, "anomaly U+%04X: %q\n", cp, t)
			}
		}
	}
	sort.Slice(folds, func(i, j int) bool { return folds[i].cp < folds[j].cp })
	f, err := os.Create(os.Args[1])
	must(err)
	defer f.Close()
	fmt.Fprintf(f, "// Generated by tokgen from SQLite %s unicode61 (defaults): every scalar value probed.\n", ver)
	fmt.Fprintf(f, "/// Inclusive codepoint ranges that separate tokens.\npub static SEPARATORS: [(u32, u32); %d] = [\n", len(seps))
	for _, s := range seps {
		fmt.Fprintf(f, "    (0x%X, 0x%X),\n", s[0], s[1])
	}
	fmt.Fprintf(f, "];\n/// Token codepoints whose folded form differs from themselves (0 = dropped).\npub static FOLDS: [(u32, u32); %d] = [\n", len(folds))
	for _, x := range folds {
		out := rune(0)
		if x.out != "" {
			out, _ = utf8.DecodeRuneInString(x.out)
		}
		fmt.Fprintf(f, "    (0x%X, 0x%X),\n", x.cp, out)
	}
	fmt.Fprintf(f, "];\n")
	fmt.Fprintf(os.Stderr, "sqlite %s: %d separator ranges, %d folds, %d anomalies\n", ver, len(seps), len(folds), anomalies)
}

// tokLines prints, for every JSON string line of the file, the (offset, term) pairs the
// product tokenizer yields for it, one JSON array per line.
func tokLines(path string) {
	raw, err := os.ReadFile(path)
	must(err)
	lines := strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n")
	db, err := sql.Open("sqlite", ":memory:")
	must(err)
	db.SetMaxOpenConns(1)
	_, err = db.Exec(`CREATE VIRTUAL TABLE tok USING fts5(name, qualified_name, signature, path, body, tokenize='unicode61', detail='full')`)
	must(err)
	_, err = db.Exec(`CREATE VIRTUAL TABLE tok_vocab USING fts5vocab(tok, 'instance')`)
	must(err)
	for i, raw := range lines {
		var l string
		must(json.Unmarshal([]byte(raw), &l))
		_, err := db.Exec(`INSERT INTO tok(rowid, body) VALUES(?, ?)`, int64(i+1), l)
		must(err)
	}
	out := make([][]any, len(lines))
	rows, err := db.Query(`SELECT doc, offset, term FROM tok_vocab ORDER BY doc, offset`)
	must(err)
	for rows.Next() {
		var d, off int64
		var t []byte
		must(rows.Scan(&d, &off, &t))
		out[d-1] = append(out[d-1], off, fmt.Sprintf("%x", t))
	}
	must(rows.Err())
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	for _, o := range out {
		if o == nil {
			o = []any{}
		}
		b, err := json.Marshal(o)
		must(err)
		w.Write(b)
		w.WriteString("\n")
	}
}
