//go:build ignore

// Writes archive_id.go, which names the SHA-256 of the static library this
// package links. The go command keys its build and test caches on Go sources
// and flags, never on the contents of an archive the cgo flags name, so
// without it a rebuilt library leaves cached test results passing and an
// existing binary unlinked. The hash in a Go source makes a changed archive a
// changed package. It runs as the second go:generate step of textindex.go,
// after the Cargo build; a library built any other way is caught by
// TestTheArchiveIDNamesTheLinkedArchive.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"os"
)

const (
	archive = "_build/release/libcodectx_textindex.a"
	output  = "archive_id.go"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "archiveid_gen:", err)
		os.Exit(1)
	}
}

func run() error {
	f, err := os.Open(archive)
	if err != nil {
		return err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return err
	}
	src := fmt.Sprintf(`// Code generated by archiveid_gen.go; DO NOT EDIT.

package textindex

// archiveSHA256 is the SHA-256 of
// %s, the library this package links. A
// rebuilt library changes this source, so the go command builds, links and
// tests again instead of serving cached results.
var archiveSHA256 = %q
`, archive, hex.EncodeToString(h.Sum(nil)))
	b, err := format.Source([]byte(src))
	if err != nil {
		return err
	}
	if old, err := os.ReadFile(output); err == nil && bytes.Equal(old, b) {
		return nil
	}
	return os.WriteFile(output, b, 0o644)
}
